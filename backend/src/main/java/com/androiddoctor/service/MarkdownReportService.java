package com.androiddoctor.service;

import com.androiddoctor.dto.DiagnosisResponse;
import com.androiddoctor.dto.FindingDto;
import org.springframework.stereotype.Service;

import java.time.ZoneId;
import java.time.format.DateTimeFormatter;

@Service
public class MarkdownReportService {
    private static final DateTimeFormatter TIME = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss XXX")
            .withZone(ZoneId.systemDefault());

    public String render(DiagnosisResponse diagnosis) {
        StringBuilder report = new StringBuilder();
        report.append("# Android Doctor 诊断报告\n\n")
                .append("> 本报告由 Android Doctor 生成。诊断结果用于辅助定位，请结合符号表、设备环境和复现过程验证。\n\n")
                .append("## 摘要\n\n")
                .append("| 项目 | 内容 |\n|---|---|\n")
                .append("| 记录 ID | `").append(diagnosis.id()).append("` |\n")
                .append("| 生成时间 | ").append(TIME.format(diagnosis.createdAt())).append(" |\n")
                .append("| 来源 | ").append(inline(diagnosis.sourceName())).append(" |\n")
                .append("| 主要分类 | ").append(inline(diagnosis.category())).append(" |\n")
                .append("| 严重程度 | ").append(inline(diagnosis.severity())).append(" |\n")
                .append("| 诊断摘要 | ").append(inline(diagnosis.summary())).append(" |\n")
                .append("| 脱敏数量 | ").append(diagnosis.redactionCount()).append(" |\n")
                .append("| 分析方式 | ").append(diagnosis.aiUsed() ? "规则 + 大模型" : "本地规则").append(" |\n\n");

        report.append("## 诊断发现\n\n");
        for (int i = 0; i < diagnosis.findings().size(); i++) {
            FindingDto finding = diagnosis.findings().get(i);
            report.append("### ").append(i + 1).append(". ").append(inline(finding.title())).append("\n\n")
                    .append("- 规则代码：`").append(finding.code()).append("`\n")
                    .append("- 分类：").append(inline(finding.category())).append("\n")
                    .append("- 严重程度：").append(inline(finding.severity())).append("\n")
                    .append("- 置信度：").append(finding.confidence()).append("%\n\n");
            appendSection(report, "命中证据", finding.evidence(), true);
            appendSection(report, "可能原因", finding.possibleCauses(), false);
            appendSection(report, "修复建议", finding.suggestions(), false);
        }

        if (diagnosis.aiAnalysis() != null && !diagnosis.aiAnalysis().isBlank()) {
            report.append("## 大模型补充意见\n\n");
            for (String line : safe(diagnosis.aiAnalysis()).split("\\R", -1)) {
                report.append("> ").append(line.isBlank() ? " " : line).append("\n");
            }
            report.append('\n');
        }

        report.append("## 脱敏日志\n\n")
                .append("原始日志未保存在报告中。以下内容已经过自动脱敏：\n\n");
        appendIndented(report, diagnosis.sanitizedLog());
        report.append("\n---\n\nGenerated by Android Doctor\n");
        return report.toString();
    }

    private void appendSection(StringBuilder report, String title, java.util.List<String> items, boolean code) {
        if (items == null || items.isEmpty()) return;
        report.append("#### ").append(title).append("\n\n");
        for (int i = 0; i < items.size(); i++) {
            if (code) {
                appendIndented(report, items.get(i));
            } else {
                report.append(i + 1).append(". ").append(inline(items.get(i))).append("\n");
            }
        }
        report.append('\n');
    }

    private void appendIndented(StringBuilder report, String value) {
        for (String line : safe(value).split("\\R", -1)) report.append("    ").append(line).append('\n');
    }

    private String inline(String value) {
        return safe(value).replace("|", "\\|").replace("`", "\\`").replace("\n", " ").replace("\r", " ");
    }

    private String safe(String value) {
        if (value == null) return "";
        return value.replace("\u0000", "").replace("<", "&lt;").replace(">", "&gt;");
    }
}

